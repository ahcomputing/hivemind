"""Avatars are self-hosted and the app ships installable icon metadata.

These tests exist because both properties are easy to regress silently: a
hardcoded avatar URL still renders robots, a missing manifest scope still
serves a page, and neither failure is visible without looking for it.
"""

import json
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from hivemind.config import Settings
from hivemind.main import create_app
from tests.conftest import FakeRepository

ICONS = Path("hivemind/static/ui/icons")
MANIFEST = Path("hivemind/static/ui/manifest.json")


def test_bootstrap_exposes_the_avatar_base(client):
    data = client.post("/api/session/bootstrap").json()
    assert data["avatar_base_url"] == "https://robohash.ahcomputing.com"


def test_returning_session_also_gets_the_avatar_base(client):
    # Two separate return paths in bootstrap(); the second one is easy to miss,
    # and the bug would only show for visitors who already have a cookie.
    client.post("/api/session/bootstrap")
    again = client.post("/api/session/bootstrap").json()
    assert again["existing"] is True
    assert again["avatar_base_url"] == "https://robohash.ahcomputing.com"


def test_avatar_base_is_configurable(settings):
    override = settings.model_copy(
        update={"avatar_base_url": "https://robohash.example.test"}
    )
    with TestClient(create_app(override, FakeRepository)) as client:
        data = client.post("/api/session/bootstrap").json()
    assert data["avatar_base_url"] == "https://robohash.example.test"


def test_default_avatar_base_is_self_hosted():
    # A misconfigured deploy must not silently fall back to the public service.
    assert "robohash.org" not in Settings(_env_file=None).avatar_base_url


def test_client_does_not_hardcode_the_public_service():
    source = Path("hivemind/static/app.js").read_text()
    assert "avatarBase" in source
    assert "robohash.org" not in source


def test_page_credits_the_cc_by_artwork(client):
    # CC BY is a licence obligation, so the build fails if the credit is lost.
    body = client.get("/").text
    assert "Zikri Kader" in body
    assert "creativecommons.org/licenses/by/3.0" in body


def test_page_no_longer_claims_avatars_come_from_a_third_party(client):
    assert "Robot avatars load from RoboHash" not in client.get("/").text


def test_page_links_icons_and_manifest(client):
    body = client.get("/").text
    for needle in (
        "/static/ui/icons/favicon.svg",
        "/static/ui/icons/apple-touch-icon.png",
        "/static/ui/manifest.json",
        'name="theme-color"',
        'property="og:image"',
    ):
        assert needle in body, needle


@pytest.mark.parametrize(
    "name",
    [
        "favicon.svg", "favicon.ico", "favicon-16.png", "favicon-32.png",
        "icon-192.png", "icon-512.png", "icon-maskable-192.png",
        "icon-maskable-512.png", "apple-touch-icon.png", "og-image.png",
    ],
)
def test_icon_asset_exists(name):
    # Generated by tools/ui/build_assets.py and committed: Inkscape is in
    # neither CI nor the container build.
    assert (ICONS / name).is_file()


def test_manifest_is_installable():
    data = json.loads(MANIFEST.read_text())
    # scope defaults to the manifest's own directory. Served from /static/,
    # that would put start_url out of scope and make the app silently
    # non-installable, with no error anywhere.
    assert data["scope"] == "/"
    assert data["start_url"] == "/"
    assert data["display"] == "standalone"

    declared = {(i["sizes"], i.get("purpose", "any")) for i in data["icons"]}
    assert ("192x192", "any") in declared
    assert ("512x512", "any") in declared
    assert any(purpose == "maskable" for _, purpose in declared)

    for icon in data["icons"]:
        assert icon["src"].startswith("/static/ui/icons/"), icon["src"]
        assert (Path("hivemind/static") / icon["src"].removeprefix("/static/")).is_file()
