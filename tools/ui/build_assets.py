#!/usr/bin/env python3
"""Build the HiveMind top-bar assets from tools/ui/brainjar.py.

Produces both delivery options so they can be compared:

  inline SVG (what the app ships) -> hivemind/templates/_topbar_art.html
                                     hivemind/static/ui/topbar-art.html

Pre-rendered sprite strips were evaluated as an alternative and dropped; the
renderer is kept behind --sprites because the same frame machinery is useful
for stills (social preview images, a favicon, docs screenshots).

Usage:  python3 tools/ui/build_assets.py [--sprites [--frames 20] [--scale 2]]
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import brainjar as bj  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROOT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(ROOT, "..", ".."))
STATIC = os.path.join(ROOT, "hivemind", "static", "ui")
SPRITES = os.path.join(STATIC, "sprites")
TEMPLATES = os.path.join(ROOT, "hivemind", "templates")

# Loop lengths chosen so each state's slowest moving part closes cleanly enough
# at the frame count below. Idle is slow, so it gets the longer loop.
LOOPS = {"idle": 4.0, "active": 2.0}


def build_inline() -> str:
    """Write the inline-SVG fragment (option A)."""
    frag = (
        "<!-- GENERATED by tools/ui/build_assets.py -- edit tools/ui/brainjar.py -->\n"
        f"{bj.svg_defs_block()}\n{bj.svg_jar_css()}\n{bj.svg_board_css()}\n"
    )
    out = os.path.join(TEMPLATES, "_topbar_art.html")
    with open(out, "w") as fh:
        fh.write(frag)
    # Same fragment under static/, so the standalone demo page can fetch it.
    os.makedirs(STATIC, exist_ok=True)
    with open(os.path.join(STATIC, "topbar-art.html"), "w") as fh:
        fh.write(frag)
    return out


def build_sprites(frames: int, scale: int) -> list[str]:
    """Render each state to a vertical sprite strip (option B)."""
    from PIL import Image

    os.makedirs(SPRITES, exist_ok=True)
    fw, fh_ = bj.BAR_W * scale, bj.BAR_H * scale
    written = []

    for state, loop in LOOPS.items():
        with tempfile.TemporaryDirectory() as tmp:
            cmds = []
            for i in range(frames):
                t = loop * i / frames
                svg = os.path.join(tmp, f"{i:03d}.svg")
                with open(svg, "w") as fh:
                    fh.write(bj.svg_bar_frame(state, t))
                cmds.append(
                    f'file-open:{svg}; export-filename:{os.path.join(tmp, f"{i:03d}.png")}; '
                    f"export-width:{fw}; export-height:{fh_}; export-do; file-close;"
                )
            subprocess.run(
                ["inkscape", "--shell"],
                input="\n".join(cmds) + "\nquit\n",
                text=True, capture_output=True, check=False,
            )
            sheet = Image.new("RGBA", (fw, fh_ * frames), (0, 0, 0, 0))
            for i in range(frames):
                png = os.path.join(tmp, f"{i:03d}.png")
                if not os.path.exists(png):
                    raise SystemExit(f"inkscape did not produce frame {i} for {state}")
                sheet.paste(Image.open(png), (0, fh_ * i))
            dest = os.path.join(SPRITES, f"bar-{state}.png")
            sheet.save(dest, optimize=True)
            written.append(dest)

    meta = os.path.join(SPRITES, "sprite.css")
    with open(meta, "w") as fh:
        fh.write(sprite_css(frames, scale))
    written.append(meta)
    return written


def sprite_css(frames: int, scale: int) -> str:
    return f"""/* GENERATED by tools/ui/build_assets.py -- option B, pre-rendered strips.
   Each strip is {frames} frames of {bj.BAR_W}x{bj.BAR_H} at {scale}x, stacked vertically. */
.hm-sprite {{
  --hm-frames: {frames};
  width: {bj.BAR_W}px;
  height: {bj.BAR_H}px;
  background-image: url("/static/ui/sprites/bar-idle.png");
  background-size: {bj.BAR_W}px {bj.BAR_H * frames}px;
  background-repeat: no-repeat;
  animation: hm-sprite-run {LOOPS['idle']}s steps({frames}) infinite;
}}
.hm-topbar[data-state="active"] .hm-sprite {{
  background-image: url("/static/ui/sprites/bar-active.png");
  animation-duration: {LOOPS['active']}s;
}}
@keyframes hm-sprite-run {{
  from {{ background-position: 0 0; }}
  to   {{ background-position: 0 -{bj.BAR_H * frames}px; }}
}}
@media (prefers-reduced-motion: reduce) {{
  .hm-sprite {{ animation: none; background-position: 0 0; }}
}}
.hm-topbar.hm-still .hm-sprite {{ animation: none; background-position: 0 0; }}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--frames", type=int, default=20)
    ap.add_argument("--scale", type=int, default=2)
    ap.add_argument("--sprites", action="store_true",
                    help="also render the pre-rendered sprite strips")
    args = ap.parse_args()

    print("inline  ->", build_inline())
    if args.sprites:
        for f in build_sprites(args.frames, args.scale):
            print("sprite  ->", f)


if __name__ == "__main__":
    main()
